import { createHash } from 'node:crypto';
import { mkdir, readFile, readdir, rm, writeFile } from 'node:fs/promises';
import { dirname, extname, relative, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const packageRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const harnessRoot = resolve(packageRoot, '..', 'factory-harness');
const sourceRoot = resolve(
  harnessRoot,
  'codex-rs',
  'app-server-protocol',
  'schema',
  'typescript',
);
const sourceSchema = resolve(
  harnessRoot,
  'codex-rs',
  'app-server-protocol',
  'schema',
  'json',
  'codex_app_server_protocol.v2.schemas.json',
);
const factoryManifestPath = resolve(
  harnessRoot,
  'factory',
  'protocol',
  'schema',
  'factory-protocol.manifest.json',
);
const destinationRoot = resolve(packageRoot, 'src', 'codex-v2', 'generated');
const check = process.argv.slice(2).includes('--check');

async function filesUnder(root) {
  const files = [];
  async function visit(directory) {
    const entries = await readdir(directory, { withFileTypes: true });
    entries.sort((left, right) => left.name.localeCompare(right.name));
    for (const entry of entries) {
      const path = resolve(directory, entry.name);
      if (entry.isDirectory()) await visit(path);
      else if (entry.isFile()) files.push(path);
    }
  }
  await visit(root);
  return files;
}

function portable(path) {
  return path.split(sep).join('/');
}

function methodsFrom(source) {
  return [...new Set([...source.matchAll(/"method": "([^"]+)"/g)].map((match) => match[1]))]
    .sort();
}

async function expectedFiles() {
  const expected = new Map();
  const typeFiles = (await filesUnder(sourceRoot)).filter((path) => extname(path) === '.ts');
  for (const path of typeFiles) {
    expected.set(portable(relative(sourceRoot, path)), await readFile(path));
  }

  const factoryManifest = JSON.parse(await readFile(factoryManifestPath, 'utf8'));
  const schemaBytes = await readFile(sourceSchema);
  const protocolManifest = {
    protocol: 'codex-app-server',
    version: { major: 2 },
    sourceCodexRevision: factoryManifest.sourceCodexRevision,
    schemaSha256: createHash('sha256').update(schemaBytes).digest('hex'),
    clientRequestMethods: methodsFrom(await readFile(resolve(sourceRoot, 'ClientRequest.ts'), 'utf8')),
    serverNotificationMethods: methodsFrom(
      await readFile(resolve(sourceRoot, 'ServerNotification.ts'), 'utf8'),
    ),
    serverRequestMethods: methodsFrom(await readFile(resolve(sourceRoot, 'ServerRequest.ts'), 'utf8')),
  };
  const manifestSource = [
    '// Generated by scripts/sync-codex-v2.mjs; do not edit.',
    `export const CODEX_V2_PROTOCOL_MANIFEST = ${JSON.stringify(protocolManifest, null, 2)} as const;`,
    '',
    'export type CodexV2ProtocolManifest = typeof CODEX_V2_PROTOCOL_MANIFEST;',
    '',
  ].join('\n');
  expected.set('factoryManifest.ts', Buffer.from(manifestSource));
  return expected;
}

async function actualFiles() {
  try {
    const files = await filesUnder(destinationRoot);
    return new Map(await Promise.all(files.map(async (path) => [
      portable(relative(destinationRoot, path)),
      await readFile(path),
    ])));
  } catch (error) {
    if (error && error.code === 'ENOENT') return new Map();
    throw error;
  }
}

function changedFiles(expected, actual) {
  const names = [...new Set([...expected.keys(), ...actual.keys()])].sort();
  return names.filter((name) => {
    const expectedBytes = expected.get(name);
    const actualBytes = actual.get(name);
    return !expectedBytes || !actualBytes || !expectedBytes.equals(actualBytes);
  });
}

const expected = await expectedFiles();
if (check) {
  const changed = changedFiles(expected, await actualFiles());
  if (changed.length > 0) {
    throw new Error(`Codex app-server V2 sync is stale: ${changed.join(', ')}`);
  }
  console.log(`Codex app-server V2 sync is current (${expected.size} files)`);
} else {
  await rm(destinationRoot, { recursive: true, force: true });
  for (const [name, bytes] of expected) {
    const destination = resolve(destinationRoot, name);
    await mkdir(dirname(destination), { recursive: true });
    await writeFile(destination, bytes);
  }
  console.log(`Synced Codex app-server V2 (${expected.size} files)`);
}

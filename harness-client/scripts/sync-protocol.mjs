import { mkdir, readFile, readdir, rm, writeFile } from 'node:fs/promises';
import { dirname, extname, relative, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const packageRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const sourceRoot = resolve(packageRoot, '..', 'factory-harness', 'factory', 'protocol', 'schema');
const destinationRoot = resolve(packageRoot, 'src', 'protocol', 'v1', 'generated');
const check = process.argv.slice(2).includes('--check');

const MANIFEST = 'factory-protocol.manifest.json';
const SCHEMA = 'factory-protocol.schema.json';

async function filesUnder(root) {
  const files = [];
  async function visit(directory) {
    const entries = await readdir(directory, { withFileTypes: true });
    entries.sort((left, right) => left.name < right.name ? -1 : left.name > right.name ? 1 : 0);
    for (const entry of entries) {
      const path = resolve(directory, entry.name);
      if (entry.isDirectory()) await visit(path);
      else if (entry.isFile()) files.push(path);
    }
  }
  await visit(root);
  return files;
}

function portable(path) {
  return path.split(sep).join('/');
}

async function expectedFiles() {
  const expected = new Map();
  for (const name of [MANIFEST, SCHEMA]) {
    expected.set(name, await readFile(resolve(sourceRoot, name)));
  }

  const typescriptRoot = resolve(sourceRoot, 'typescript');
  const typeFiles = (await filesUnder(typescriptRoot)).filter((path) => extname(path) === '.ts');
  for (const path of typeFiles) {
    expected.set(portable(relative(sourceRoot, path)), await readFile(path));
  }

  const exports = typeFiles.map((path) => {
    const relativeType = portable(relative(typescriptRoot, path)).replace(/\.ts$/, '');
    const typeName = relativeType.split('/').at(-1);
    return `export type { ${typeName} } from './typescript/${relativeType}.js';`;
  });
  const manifest = JSON.parse(await readFile(resolve(sourceRoot, MANIFEST), 'utf8'));
  const generatedIndex = [
    '// Generated by scripts/sync-protocol.mjs; do not edit.',
    ...exports,
    "export { FACTORY_PROTOCOL_MANIFEST, FACTORY_PROTOCOL_RANGE } from './manifest.js';",
    '',
  ].join('\n');
  const generatedManifest = [
    '// Generated by scripts/sync-protocol.mjs; do not edit.',
    "import type { ProtocolManifest } from './typescript/ProtocolManifest.js';",
    "import type { ProtocolRange } from './typescript/ProtocolRange.js';",
    '',
    `export const FACTORY_PROTOCOL_MANIFEST = ${JSON.stringify(manifest, null, 2)} as const satisfies ProtocolManifest;`,
    'export const FACTORY_PROTOCOL_RANGE = {',
    '  minimum: FACTORY_PROTOCOL_MANIFEST.version,',
    '  maximum: FACTORY_PROTOCOL_MANIFEST.version,',
    '} as const satisfies ProtocolRange;',
    '',
  ].join('\n');
  expected.set('index.ts', Buffer.from(generatedIndex));
  expected.set('manifest.ts', Buffer.from(generatedManifest));
  return expected;
}

async function actualFiles() {
  try {
    const files = await filesUnder(destinationRoot);
    return new Map(await Promise.all(files.map(async (path) => [
      portable(relative(destinationRoot, path)),
      await readFile(path),
    ])));
  } catch (error) {
    if (error && error.code === 'ENOENT') return new Map();
    throw error;
  }
}

function compare(expected, actual) {
  const names = [...new Set([...expected.keys(), ...actual.keys()])].sort();
  return names.filter((name) => {
    const expectedBytes = expected.get(name);
    const actualBytes = actual.get(name);
    return !expectedBytes || !actualBytes || !expectedBytes.equals(actualBytes);
  });
}

const expected = await expectedFiles();
if (check) {
  const changed = compare(expected, await actualFiles());
  if (changed.length > 0) {
    throw new Error(`Factory Protocol sync is stale: ${changed.join(', ')}`);
  }
  console.log(`Factory Protocol sync is current (${expected.size} files)`);
} else {
  await rm(destinationRoot, { recursive: true, force: true });
  for (const [name, bytes] of expected) {
    const destination = resolve(destinationRoot, name);
    await mkdir(dirname(destination), { recursive: true });
    await writeFile(destination, bytes);
  }
  console.log(`Synced Factory Protocol V1 (${expected.size} files)`);
}

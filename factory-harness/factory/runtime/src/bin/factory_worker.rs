#[derive(Debug, Parser)]
#[command(
    name = "factory-worker",
    version,
    about = "Run durable Software Factory jobs through the native Codex runtime"
)]
struct WorkerArgs {
    /// PostgreSQL connection URL used by the durable coordinator.
    #[arg(long, env = "FACTORY_DATABASE_URL")]
    database_url: String,

    /// Base URL of the factoryd API used for fenced Factory thread state.
    #[arg(long, env = "FACTORYD_URL", default_value = "http://127.0.0.1:8787")]
    factoryd_url: String,

    /// Stable identity for this worker process. A unique value is generated when omitted.
    #[arg(long, env = "FACTORY_WORKER_ID")]
    worker_id: Option<String>,

    /// Maximum number of operations executed concurrently.
    #[arg(long, env = "FACTORY_WORKER_SLOTS", default_value_t = 4)]
    slots: usize,

    /// Attempt lease duration in whole seconds.
    #[arg(long, env = "FACTORY_WORKER_LEASE_SECONDS", default_value_t = 300)]
    lease_seconds: u64,

    /// Delay between durable work polls in milliseconds.
    #[arg(long, env = "FACTORY_WORKER_POLL_MILLISECONDS", default_value_t = 500)]
    poll_milliseconds: u64,

    /// Time allowed for active operations to stop after Ctrl-C.
    #[arg(
        long,
        env = "FACTORY_WORKER_SHUTDOWN_GRACE_SECONDS",
        default_value_t = 30
    )]
    shutdown_grace_seconds: u64,

    /// Codex home containing config and provider credentials.
    #[arg(long, env = "CODEX_HOME")]
    codex_home: Option<PathBuf>,

    /// Provider profile used by the native Codex runtime.
    #[arg(long, env = "FACTORY_PROVIDER_ADAPTER")]
    provider: String,

    /// Responses endpoint used by Codex. Adapter profiles point at their local bridge.
    #[arg(long, env = "FACTORY_PROVIDER_BASE_URL")]
    provider_base_url: Option<String>,

    /// Model used for Factory jobs. Defaults to the selected provider profile.
    #[arg(long, env = "FACTORY_MODEL")]
    model: Option<String>,

    /// Optional Codex model catalog generated by the provider adapter.
    #[arg(long)]
    model_catalog_json: Option<PathBuf>,

    /// Per-job execution-environment backend.
    #[arg(
        long,
        env = "FACTORY_EXECUTION_ENVIRONMENT_BACKEND",
        default_value = "docker"
    )]
    execution_environment_backend: String,

    /// Numeric user identity shared by the worker and Kubernetes execution Pod.
    #[arg(long, env = "FACTORY_RUN_AS_UID")]
    run_as_uid: Option<String>,

    /// Numeric group identity shared by the worker and Kubernetes execution Pod.
    #[arg(long, env = "FACTORY_RUN_AS_GID")]
    run_as_gid: Option<String>,

    /// Kubernetes namespace used when the execution-environment backend is Kubernetes.
    #[arg(long, env = "FACTORY_KUBERNETES_NAMESPACE", default_value = "default")]
    kubernetes_namespace: String,

    /// Image containing `codex exec-server` for Kubernetes execution Pods.
    #[arg(long, env = "FACTORY_KUBERNETES_IMAGE")]
    kubernetes_image: Option<String>,

    /// Existing PVC containing coordinator-managed workspaces.
    #[arg(long, env = "FACTORY_KUBERNETES_WORKSPACE_PVC")]
    kubernetes_workspace_pvc: Option<String>,

    /// Absolute path represented by the root of the Kubernetes workspace PVC.
    #[arg(
        long,
        env = "FACTORY_KUBERNETES_WORKSPACE_ROOT",
        default_value = "/workspaces"
    )]
    kubernetes_workspace_root: String,

    /// Optional Kubernetes RuntimeClass, such as `kata`; omitted means the cluster default.
    #[arg(long, env = "FACTORY_KUBERNETES_RUNTIME_CLASS")]
    kubernetes_runtime_class: Option<String>,

    /// Time allowed for Pod creation, readiness, and normal deletion.
    #[arg(
        long,
        env = "FACTORY_KUBERNETES_READINESS_TIMEOUT_SECONDS",
        default_value_t = 120
    )]
    kubernetes_readiness_timeout_seconds: u64,

    #[arg(long, env = "FACTORY_KUBERNETES_CPU_REQUEST_MILLIS")]
    kubernetes_cpu_request_millis: Option<u32>,

    #[arg(long, env = "FACTORY_KUBERNETES_MEMORY_REQUEST_MIB")]
    kubernetes_memory_request_mib: Option<u32>,

    #[arg(long, env = "FACTORY_KUBERNETES_CPU_LIMIT_MILLIS")]
    kubernetes_cpu_limit_millis: Option<u32>,

    #[arg(long, env = "FACTORY_KUBERNETES_MEMORY_LIMIT_MIB")]
    kubernetes_memory_limit_mib: Option<u32>,
}

fn main() -> Result<()> {
    ensure_rustls_crypto_provider();
    arg0_dispatch_or_else(|arg0_paths: Arg0DispatchPaths| async move {
        run_worker(WorkerArgs::parse(), arg0_paths).await
    })
}

async fn run_worker(args: WorkerArgs, arg0_paths: Arg0DispatchPaths) -> Result<()> {
    validate_args(&args)?;
    let provisioner = build_execution_environment_provisioner(&args).await?;
    let worker_id = args.worker_id.unwrap_or_else(generated_worker_id);

    let store = CoordinatorStore::connect_for_worker(&args.database_url, args.slots)
        .await
        .context("connect factory worker to PostgreSQL")?;
    store
        .migrate()
        .await
        .context("apply Factory coordinator migrations")?;

    let profile = provider_profile(&args.provider)
        .ok_or_else(|| anyhow::anyhow!("unknown provider profile {}", args.provider))?;
    let provider_base_url = args
        .provider_base_url
        .filter(|value| !value.trim().is_empty())
        .unwrap_or_else(|| profile.base_urls[0].url.to_string());
    let model = args
        .model
        .filter(|value| !value.trim().is_empty())
        .unwrap_or_else(|| profile.default_model.to_string());
    let execution_profile = ExecutionProfile {
        provider: profile.id.to_string(),
        model: model.clone(),
    };
    let model_catalog_json = args
        .model_catalog_json
        .or_else(|| nonempty_env_path("FACTORY_MODEL_CATALOG_JSON"))
        .filter(|path| !path.as_os_str().is_empty());
    let provider =
        CodexProviderSelection::for_profile(profile, provider_base_url, model, model_catalog_json);

    let start_args = build_worker_start_args(WorkerBootstrap {
        arg0_paths,
        workspace_cwd: std::env::current_dir().context("read worker current directory")?,
        codex_home: args.codex_home,
        provider,
    })
    .await
    .context("build native Codex worker runtime")?;
    let executor = CodexOperationExecutor::new(
        store.clone(),
        start_args,
        args.factoryd_url.clone(),
        execution_profile.clone(),
        provisioner,
    )
    .map_err(anyhow::Error::msg)
    .context("configure Codex operation executor")?;
    let runner = DurableRunner::new(
        store.clone(),
        executor,
        RunnerConfig {
            worker_id: CoordinatorInstanceId::new(worker_id.clone()),
            lease_duration: Duration::from_secs(args.lease_seconds),
            poll_interval: Duration::from_millis(args.poll_milliseconds),
            shutdown_grace: Duration::from_secs(args.shutdown_grace_seconds),
            slots: args.slots,
            execution_profile: Some(execution_profile),
        },
    )
    .context("configure durable worker")?;

    println!(
        "factory worker {worker_id} starting with {} slots",
        args.slots
    );
    let shutdown = CancellationHandle::default();
    let run = runner.run(shutdown.clone());
    tokio::pin!(run);
    tokio::select! {
        result = &mut run => result.context("run durable Factory worker")?,
        signal = worker_shutdown_signal() => {
            signal?;
            shutdown.cancel();
            run.await.context("stop durable Factory worker")?;
        }
    }

    store.close().await;
    Ok(())
}

#[cfg(unix)]
async fn worker_shutdown_signal() -> Result<()> {
    let mut terminate = tokio::signal::unix::signal(tokio::signal::unix::SignalKind::terminate())
        .context("install Factory worker SIGTERM handler")?;
    tokio::select! {
        signal = tokio::signal::ctrl_c() => {
            signal.context("wait for Factory worker Ctrl-C")
        }
        _ = terminate.recv() => Ok(()),
    }
}

#[cfg(not(unix))]
async fn worker_shutdown_signal() -> Result<()> {
    tokio::signal::ctrl_c()
        .await
        .context("wait for Factory worker Ctrl-C")
}

fn nonempty_env_path(name: &str) -> Option<PathBuf> {
    std::env::var_os(name)
        .filter(|value| !value.is_empty())
        .map(PathBuf::from)
}

async fn build_execution_environment_provisioner(
    args: &WorkerArgs,
) -> Result<Arc<dyn ExecutionEnvironmentProvisioner>> {
    match args.execution_environment_backend.trim() {
        DOCKER_EXECUTION_ENVIRONMENT_BACKEND => Ok(Arc::new(
            DockerExecutionEnvironmentProvisioner::discover()
                .await
                .context("discover Docker execution-environment template")?,
        )),
        KUBERNETES_EXECUTION_ENVIRONMENT_BACKEND => {
            let config = KubernetesExecutionEnvironmentConfig {
                namespace: args.kubernetes_namespace.clone(),
                image: args.kubernetes_image.clone().unwrap_or_default(),
                workspace_pvc: args.kubernetes_workspace_pvc.clone().unwrap_or_default(),
                workspace_root: args.kubernetes_workspace_root.clone(),
                runtime_class_name: args.kubernetes_runtime_class.clone(),
                run_as_uid: parse_run_as_id("FACTORY_RUN_AS_UID", args.run_as_uid.as_deref())?,
                run_as_gid: parse_run_as_id("FACTORY_RUN_AS_GID", args.run_as_gid.as_deref())?,
                readiness_timeout: Duration::from_secs(args.kubernetes_readiness_timeout_seconds),
                resources: KubernetesResourceConfig {
                    cpu_request_millis: args.kubernetes_cpu_request_millis,
                    memory_request_mib: args.kubernetes_memory_request_mib,
                    cpu_limit_millis: args.kubernetes_cpu_limit_millis,
                    memory_limit_mib: args.kubernetes_memory_limit_mib,
                },
            };
            Ok(Arc::new(
                KubernetesExecutionEnvironmentProvisioner::discover(config)
                    .await
                    .context("configure Kubernetes execution-environment backend")?,
            ))
        }
        "" => Err(anyhow::anyhow!(
            "execution-environment backend must not be empty"
        )),
        backend => Err(anyhow::anyhow!(
            "unsupported execution-environment backend {backend}"
        )),
    }
}

fn parse_run_as_id(field: &str, value: Option<&str>) -> Result<Option<i64>> {
    let Some(value) = value.map(str::trim).filter(|value| !value.is_empty()) else {
        return Ok(None);
    };
    let value = value
        .parse::<i64>()
        .with_context(|| format!("{field} must be a non-negative integer"))?;
    ensure!(value >= 0, "{field} must be a non-negative integer");
    Ok(Some(value))
}

fn validate_args(args: &WorkerArgs) -> Result<()> {
    ensure!(
        !args.database_url.trim().is_empty(),
        "database URL must not be empty"
    );
    ensure!(
        !args.factoryd_url.trim().is_empty(),
        "factoryd URL must not be empty"
    );
    if let Some(worker_id) = &args.worker_id {
        ensure!(!worker_id.trim().is_empty(), "worker ID must not be empty");
    }
    ensure!(
        !args.provider.trim().is_empty(),
        "provider must not be empty"
    );
    ensure!(
        !args.execution_environment_backend.trim().is_empty(),
        "execution-environment backend must not be empty"
    );
    ensure!(
        (1..=CoordinatorStore::MAX_WORKER_SLOTS).contains(&args.slots),
        "worker slots must be between 1 and {}",
        CoordinatorStore::MAX_WORKER_SLOTS
    );
    Ok(())
}

fn generated_worker_id() -> String {
    let started_at = SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .unwrap_or_default()
        .as_millis();
    format!("factory-worker-{}-{started_at}", process::id())
}

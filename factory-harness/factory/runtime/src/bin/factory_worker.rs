use std::path::PathBuf;
use std::process;
use std::time::Duration;
use std::time::SystemTime;
use std::time::UNIX_EPOCH;

use anyhow::Context;
use anyhow::Result;
use anyhow::ensure;
use clap::Parser;
use codex_arg0::Arg0DispatchPaths;
use codex_arg0::arg0_dispatch_or_else;
use factory_coordinator::CancellationHandle;
use factory_coordinator::CoordinatorInstanceId;
use factory_coordinator::CoordinatorStore;
use factory_coordinator::DurableRunner;
use factory_coordinator::ExecutionProfile;
use factory_coordinator::RunnerConfig;
use factory_providers::CodexProviderSelection;
use factory_providers::provider_profile;
use factory_runtime::bootstrap::WorkerBootstrap;
use factory_runtime::bootstrap::build_worker_start_args;
use factory_runtime::executor::CodexOperationExecutor;

#[derive(Debug, Parser)]
#[command(
    name = "factory-worker",
    version,
    about = "Run durable Software Factory jobs through the native Codex runtime"
)]
struct WorkerArgs {
    /// PostgreSQL connection URL used by the durable coordinator.
    #[arg(long, env = "FACTORY_DATABASE_URL")]
    database_url: String,

    /// Base URL of the factoryd API used for fenced Factory thread state.
    #[arg(long, env = "FACTORYD_URL", default_value = "http://127.0.0.1:8787")]
    factoryd_url: String,

    /// Stable identity for this worker process. A unique value is generated when omitted.
    #[arg(long, env = "FACTORY_WORKER_ID")]
    worker_id: Option<String>,

    /// Maximum number of operations executed concurrently.
    #[arg(long, env = "FACTORY_WORKER_SLOTS", default_value_t = 4)]
    slots: usize,

    /// Attempt lease duration in whole seconds.
    #[arg(long, env = "FACTORY_WORKER_LEASE_SECONDS", default_value_t = 300)]
    lease_seconds: u64,

    /// Delay between durable work polls in milliseconds.
    #[arg(long, env = "FACTORY_WORKER_POLL_MILLISECONDS", default_value_t = 500)]
    poll_milliseconds: u64,

    /// Time allowed for active operations to stop after Ctrl-C.
    #[arg(
        long,
        env = "FACTORY_WORKER_SHUTDOWN_GRACE_SECONDS",
        default_value_t = 30
    )]
    shutdown_grace_seconds: u64,

    /// Codex home containing config and provider credentials.
    #[arg(long, env = "CODEX_HOME")]
    codex_home: Option<PathBuf>,

    /// Provider profile used by the native Codex runtime.
    #[arg(long, env = "FACTORY_PROVIDER_ADAPTER")]
    provider: String,

    /// Responses endpoint used by Codex. Adapter profiles point at their local bridge.
    #[arg(long, env = "FACTORY_PROVIDER_BASE_URL")]
    provider_base_url: Option<String>,

    /// Model used for Factory jobs. Defaults to the selected provider profile.
    #[arg(long, env = "FACTORY_MODEL")]
    model: Option<String>,

    /// Optional Codex model catalog generated by the provider adapter.
    #[arg(long)]
    model_catalog_json: Option<PathBuf>,
}

fn main() -> Result<()> {
    arg0_dispatch_or_else(|arg0_paths: Arg0DispatchPaths| async move {
        run_worker(WorkerArgs::parse(), arg0_paths).await
    })
}

async fn run_worker(args: WorkerArgs, arg0_paths: Arg0DispatchPaths) -> Result<()> {
    validate_args(&args)?;
    let worker_id = args.worker_id.unwrap_or_else(generated_worker_id);

    let store = CoordinatorStore::connect_for_worker(&args.database_url, args.slots)
        .await
        .context("connect factory worker to PostgreSQL")?;
    store
        .migrate()
        .await
        .context("apply Factory coordinator migrations")?;

    let profile = provider_profile(&args.provider)
        .ok_or_else(|| anyhow::anyhow!("unknown provider profile {}", args.provider))?;
    let provider_base_url = args
        .provider_base_url
        .filter(|value| !value.trim().is_empty())
        .unwrap_or_else(|| profile.base_urls[0].url.to_string());
    let model = args
        .model
        .filter(|value| !value.trim().is_empty())
        .unwrap_or_else(|| profile.default_model.to_string());
    let execution_profile = ExecutionProfile {
        provider: profile.id.to_string(),
        model: model.clone(),
    };
    let model_catalog_json = args
        .model_catalog_json
        .or_else(|| nonempty_env_path("FACTORY_MODEL_CATALOG_JSON"))
        .filter(|path| !path.as_os_str().is_empty());
    let provider =
        CodexProviderSelection::for_profile(profile, provider_base_url, model, model_catalog_json);

    let start_args = build_worker_start_args(WorkerBootstrap {
        arg0_paths,
        workspace_cwd: std::env::current_dir().context("read worker current directory")?,
        codex_home: args.codex_home,
        provider,
    })
    .await
    .context("build native Codex worker runtime")?;
    let executor = CodexOperationExecutor::new(
        store.clone(),
        start_args,
        args.factoryd_url.clone(),
        execution_profile.clone(),
    )
    .map_err(anyhow::Error::msg)
    .context("configure Codex operation executor")?;
    let runner = DurableRunner::new(
        store.clone(),
        executor,
        RunnerConfig {
            worker_id: CoordinatorInstanceId::new(worker_id.clone()),
            lease_duration: Duration::from_secs(args.lease_seconds),
            poll_interval: Duration::from_millis(args.poll_milliseconds),
            shutdown_grace: Duration::from_secs(args.shutdown_grace_seconds),
            slots: args.slots,
            execution_profile: Some(execution_profile),
        },
    )
    .context("configure durable worker")?;

    println!(
        "factory worker {worker_id} starting with {} slots",
        args.slots
    );
    let shutdown = CancellationHandle::default();
    let run = runner.run(shutdown.clone());
    tokio::pin!(run);
    tokio::select! {
        result = &mut run => result.context("run durable Factory worker")?,
        signal = worker_shutdown_signal() => {
            signal?;
            shutdown.cancel();
            run.await.context("stop durable Factory worker")?;
        }
    }

    store.close().await;
    Ok(())
}

#[cfg(unix)]
async fn worker_shutdown_signal() -> Result<()> {
    let mut terminate = tokio::signal::unix::signal(tokio::signal::unix::SignalKind::terminate())
        .context("install Factory worker SIGTERM handler")?;
    tokio::select! {
        signal = tokio::signal::ctrl_c() => {
            signal.context("wait for Factory worker Ctrl-C")
        }
        _ = terminate.recv() => Ok(()),
    }
}

#[cfg(not(unix))]
async fn worker_shutdown_signal() -> Result<()> {
    tokio::signal::ctrl_c()
        .await
        .context("wait for Factory worker Ctrl-C")
}

fn nonempty_env_path(name: &str) -> Option<PathBuf> {
    std::env::var_os(name)
        .filter(|value| !value.is_empty())
        .map(PathBuf::from)
}

fn validate_args(args: &WorkerArgs) -> Result<()> {
    ensure!(
        !args.database_url.trim().is_empty(),
        "database URL must not be empty"
    );
    ensure!(
        !args.factoryd_url.trim().is_empty(),
        "factoryd URL must not be empty"
    );
    if let Some(worker_id) = &args.worker_id {
        ensure!(!worker_id.trim().is_empty(), "worker ID must not be empty");
    }
    ensure!(
        !args.provider.trim().is_empty(),
        "provider must not be empty"
    );
    ensure!(
        (1..=CoordinatorStore::MAX_WORKER_SLOTS).contains(&args.slots),
        "worker slots must be between 1 and {}",
        CoordinatorStore::MAX_WORKER_SLOTS
    );
    Ok(())
}

fn generated_worker_id() -> String {
    let started_at = SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .unwrap_or_default()
        .as_millis();
    format!("factory-worker-{}-{started_at}", process::id())
}

const GENERATED_NOTICE: &str =
    "Generated by `cargo run -p factory-protocol --bin export_factory_protocol`; do not edit.";

#[derive(Debug, Parser)]
struct Args {
    /// Verify checked-in artifacts instead of overwriting them.
    #[arg(long)]
    check: bool,

    /// Run a local codec smoke command without starting Codex or a model turn.
    #[arg(long)]
    verify_codec: bool,

    /// Output directory. Defaults to the crate-owned `schema` directory.
    #[arg(long)]
    out_dir: Option<PathBuf>,
}

fn main() -> Result<()> {
    let args = Args::parse();
    let checked_in = args
        .out_dir
        .unwrap_or_else(|| PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("schema"));

    if args.check {
        let temporary = TempDir::new().context("create protocol export directory")?;
        generate(temporary.path())?;
        compare_trees(&checked_in, temporary.path())?;
        println!(
            "Factory Protocol artifacts are current: {}",
            checked_in.display()
        );
    } else {
        generate(&checked_in)?;
        println!(
            "Generated Factory Protocol artifacts: {}",
            checked_in.display()
        );
    }

    if args.verify_codec {
        verify_codec()?;
        println!("Factory Protocol codec smoke command passed");
    }

    Ok(())
}


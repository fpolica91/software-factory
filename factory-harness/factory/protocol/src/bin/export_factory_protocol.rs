fn verify_server_pair(index: usize, method: &str, params: Value, response: Value) -> Result<()> {
    let request_id = format!("server-pair-{index}");
    let decoded = app_server_v2::server_request_from_app_server_json(serde_json::json!({
        "id": request_id,
        "method": method,
        "params": params
    }))?;
    let request = match &decoded {
        FactoryDecodedServerRequest::Known { request, raw } => {
            ensure!(raw.method.as_str() == method);
            request
        }
        FactoryDecodedServerRequest::Unknown { .. } => {
            bail!("supported server request decoded as unknown: {method}")
        }
    };
    let typed_response: FactoryServerResponse = serde_json::from_value(serde_json::json!({
        "id": request_id,
        "method": method,
        "response": response
    }))?;
    let encoded = app_server_v2::server_response_to_app_server_json(request, &typed_response)?;
    ensure!(encoded.get("id").and_then(Value::as_str) == Some(request_id.as_str()));
    ensure!(encoded.get("result").is_some());
    Ok(())
}

fn generate(out_dir: &Path) -> Result<()> {
    fs::create_dir_all(out_dir)
        .with_context(|| format!("create export directory {}", out_dir.display()))?;

    let mut schema = serde_json::to_value(schema_for!(FactoryProtocolSchema))?;
    schema
        .as_object_mut()
        .context("Factory protocol schema root must be an object")?
        .insert(
            "$comment".to_string(),
            Value::String(GENERATED_NOTICE.to_string()),
        );
    let schema_bytes = pretty_json_bytes(&schema)?;
    let schema_digest = hex_digest(&schema_bytes);
    ensure!(
        schema_digest == FACTORY_PROTOCOL_SCHEMA_SHA256,
        "Factory Protocol schema digest changed: generated {schema_digest}, expected {FACTORY_PROTOCOL_SCHEMA_SHA256}"
    );
    fs::write(out_dir.join("factory-protocol.schema.json"), &schema_bytes)
        .context("write Factory protocol JSON Schema")?;

    let manifest = ProtocolManifest::current();
    fs::write(
        out_dir.join("factory-protocol.manifest.json"),
        pretty_json_bytes(&serde_json::to_value(manifest)?)?,
    )
    .context("write Factory protocol manifest")?;

    let typescript_dir = out_dir.join("typescript");
    if typescript_dir.exists() {
        fs::remove_dir_all(&typescript_dir)
            .with_context(|| format!("replace {}", typescript_dir.display()))?;
    }
    fs::create_dir_all(&typescript_dir)?;
    FactoryProtocolSchema::export_all_to(&typescript_dir)
        .context("export Factory protocol TypeScript")?;

    Ok(())
}

fn pretty_json_bytes(value: &Value) -> Result<Vec<u8>> {
    let mut bytes = serde_json::to_vec_pretty(value)?;
    bytes.push(b'\n');
    Ok(bytes)
}

fn hex_digest(bytes: &[u8]) -> String {
    let digest = Sha256::digest(bytes);
    digest.iter().map(|byte| format!("{byte:02x}")).collect()
}

fn compare_trees(expected: &Path, actual: &Path) -> Result<()> {
    let expected_files = read_tree(expected)?;
    let actual_files = read_tree(actual)?;
    if expected_files != actual_files {
        let expected_names: Vec<_> = expected_files.keys().collect();
        let actual_names: Vec<_> = actual_files.keys().collect();
        bail!(
            "Factory Protocol artifacts are stale; expected files {expected_names:?}, generated files {actual_names:?}"
        );
    }
    Ok(())
}

fn read_tree(root: &Path) -> Result<BTreeMap<PathBuf, Vec<u8>>> {
    let mut files = BTreeMap::new();
    collect_files(root, root, &mut files)?;
    Ok(files)
}

fn collect_files(
    root: &Path,
    directory: &Path,
    files: &mut BTreeMap<PathBuf, Vec<u8>>,
) -> Result<()> {
    let mut entries = fs::read_dir(directory)
        .with_context(|| format!("read export directory {}", directory.display()))?
        .collect::<std::io::Result<Vec<_>>>()?;
    entries.sort_by_key(|entry| entry.file_name());

    for entry in entries {
        let path = entry.path();
        if path.is_dir() {
            collect_files(root, &path, files)?;
        } else {
            files.insert(path.strip_prefix(root)?.to_path_buf(), fs::read(&path)?);
        }
    }
    Ok(())
}
